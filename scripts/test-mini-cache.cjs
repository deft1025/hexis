const assert = require('node:assert/strict');
const { create: cache } = require('../miniprogram/lib/data-cache');
const { create: core } = require('../miniprogram/lib/core');

(async () => {
  let now = 0, calls = 0, fail = false;
  const options = { now: () => now, ttl: 100, versionTTL: 10 };
  const request = async path => { calls++; if (fail) throw Error('offline'); return { path, calls }; };
  const a = cache('test-api:preview', request, options);
  const b = cache('test-api:preview', request, options);
  const [first, second] = await Promise.all([a('/catalog?patch=1'), b('/catalog?patch=1')]);
  assert.strictEqual(first, second);
  assert.equal(calls, 1, 'concurrent pages must share a request');
  await b('/catalog?patch=2');
  await cache('test-api:formal', request, options)('/catalog?patch=1');
  await cache('other-api:preview', request, options)('/catalog?patch=1');
  assert.equal(calls, 4, 'patch, mode and API origin must remain isolated');
  await a('/api/v1/patches/latest');
  assert.equal(a.isStale(), false);
  now = 10;
  assert.equal(a.isStale(), true);
  await a('/api/v1/patches/latest');
  await b('/catalog?patch=1');
  assert.equal(calls, 6, 'version checks must not expire catalogs early');
  now = 100;
  await b('/catalog?patch=1');
  assert.equal(calls, 7, 'same-patch content must refresh after TTL');
  fail = true;
  await assert.rejects(a('/failed'), /offline/);
  fail = false;
  await b('/failed');
  assert.equal(calls, 9, 'failed responses must not be cached');
  a.invalidate();
  assert.equal(b.isStale(), true);
  await b('/catalog?patch=1');
  assert.equal(calls, 10, 'manual refresh must clear the shared scope');

  let release;
  const pending = cache('pending', () => new Promise(resolve => { release = resolve; }));
  const old = pending('/x');
  await Promise.resolve();
  pending.invalidate();
  const fresh = cache('pending', async () => 'new')('/x');
  release('old');
  assert.equal(await old, 'old');
  assert.equal(await fresh, 'new');
  assert.equal(await pending('/x'), 'new', 'old pending response must not repopulate an invalidated cache');

  const data = Object.fromEntries([['champions',173],['augments',223],['items',194],['guides',284]].map(([kind,count]) => [kind, Array.from({length:count}, (_,i) => kind === 'guides' ? { id:'g'+i,title:'Guide '+i,category:'fun',champion_ids:['hero0'],stages:[] } : {id:(kind==='champions'?'hero':'row')+i,name_zh:'Name '+i,description:'Before',price:100})]));
  let version = '16.20', network = 0;
  const fetchPage = async path => {
    network++;
    if (path === '/api/v1/patches/latest') return { version };
    const url = new URL(path, 'https://example.com');
    const kind = url.pathname.split('/').pop(), offset = Number(url.searchParams.get('offset'));
    return { patch:version, items:data[kind].slice(offset,offset+100) };
  };
  const page = scope => core({previewGuides:true,read:()=>null,write(){},notice(){},render(){},request:cache(scope,fetchPage)});
  const page1 = page('integration');
  page1.enter('detail',{kind:'champions',id:'hero0'});
  await page1.load();
  assert.equal(network,11);
  const page2 = page('integration');
  page2.enter('guides');
  await page2.load();
  assert.equal(network,11,'opening another page must make zero extra API requests');
  assert.equal(page1.view().mode,'detail','pages must retain independent UI state');
  assert.equal(page2.view().counts.guides,284);
  cache('integration',fetchPage).invalidate();
  data.augments = data.augments.map(row=>({...row,description:'Updated'}));
  await page2.load();
  assert.equal(network,22);
  page2.enter('detail',{kind:'augments',id:'row0'});
  assert.equal(page2.view().detail.description,'Updated');
  version='16.21';
  cache('integration',fetchPage).invalidate();
  await page1.load();
  assert.equal(page1.view().patch,'16.21');
  console.log('PASS: shared requests, TTL, failed retry, API/patch/preview isolation, forced refresh, invalidation races, independent pages and 11 -> 0 requests on page navigation');
})().catch(error => {console.error(error);process.exitCode=1;});
